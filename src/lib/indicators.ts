export const INDICATOR_KEYS = Object.keys(INDICATORS) as IndicatorKey[]

export function indicatorsFor(category: IndicatorCategory): IndicatorMeta[] {
  return INDICATOR_KEYS.map((k) => INDICATORS[k]).filter((m) => m.category === category)
}

export function formatIndicator(key: IndicatorKey, value: number): string {
  const m = INDICATORS[key]
  if (!isFinite(value)) return '—'
  return `${value.toFixed(m.decimals)} ${m.unit}`
}
